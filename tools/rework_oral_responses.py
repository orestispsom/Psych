def update_oral_data(oral_file: Path) -> None:
    content = oral_file.read_text(encoding="utf-8")
    m = re.search(r"const\s+oralData\s*=\s*(\[.+\])\s*;?\s*(?:export\s+default\s+oralData;?)?$", content, re.DOTALL)
    if not m:
        raise SystemExit("Could not parse oralData structure from oral.js")

    data = json.loads(m.group(1))

    updated_count = 0
    for g in data:
        for t in g.get("topics", []):
            subtopics = t.get("subtopics") or []
            if subtopics:
                for st in subtopics:
                    for q in st.get("questions", []):
                        qid = q["id"]
                        if qid in ORAL_ANSWERS:
                            q["answer"] = ORAL_ANSWERS[qid]
                            updated_count += 1
                        else:
                            print(f"WARNING: missing answer for {qid}")
            else:
                for q in t.get("questions", []):
                    qid = q["id"]
                    if qid in ORAL_ANSWERS:
                        q["answer"] = ORAL_ANSWERS[qid]
                        updated_count += 1
                    else:
                        print(f"WARNING: missing answer for {qid}")

    if updated_count != 129:
        raise SystemExit(f"Expected 129 updated questions, got {updated_count}")

    rendered = "const oralData = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n\nexport default oralData;\n"
    oral_file.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"Successfully updated and validated all {updated_count}/129 oral answers in {oral_file}!")


if __name__ == "__main__":
    import sys
    target = Path("src/data/oral.js")
    if len(sys.argv) > 1:
        target = Path(sys.argv[1])
    update_oral_data(target)
