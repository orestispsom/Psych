export function expandMatchingSetsWithBoardItems(sets) {
  return sets.map(set => {
    const additions = boardMatchingExpansions[set.id];
    if (!additions?.length) return set;
    return {
      ...set,
      items: [...set.items, ...additions],
    };
  });
}

